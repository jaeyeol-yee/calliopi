// Scenario → VHS tape. The tape never sees the scenario's replies: the faux model streams them, and
// the tape only types prompts and waits for the reply to appear on screen.
import type { ReplyBlock, Scenario } from './scenario.ts';

export interface TapeEnv {
  output: string;
  workdir: string;
  env: Record<string, string>;
  /** Full command line that starts Pi in the workdir. */
  pi: string;
}

/** A VHS string literal. VHS has no escapes, so pick a quote the text does not contain. */
export function vhsString(text: string): string {
  for (const q of ['"', "'", '`']) if (!text.includes(q)) return q + text + q;
  throw new Error(`VHS 문자열에 ", ', \` 를 모두 쓸 수는 없습니다: ${text}`);
}

/** VHS regex literal: /…/ with slashes escaped. */
export function vhsRegex(source: string): string {
  return '/' + source.replace(/\//g, '\\/') + '/';
}

const escapeRegex = (s: string) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

/**
 * Default wait: the last words of the reply's last text block, so the tape moves on only once the
 * reply has finished streaming. Kept short so a wrapped line still matches.
 */
export function defaultWait(reply: ReplyBlock[] | undefined): string | undefined {
  const text = reply?.filter((b): b is { text: string } => 'text' in b).at(-1)?.text;
  // Markdown markers are rendered away, so match only plain words at the end of the last line.
  const line = text?.split('\n').map((l) => l.trim()).filter(Boolean).at(-1);
  const tail = line?.match(/[^*_`[\]()#>|]+$/)?.[0].trim().split(/\s+/).slice(-2).join(' ');
  return tail ? escapeRegex(tail) : undefined;
}

/** Type text line by line: a newline in the editor is Shift+Enter, a plain Enter would send. */
function typeLines(text: string): string[] {
  return text.split('\n').flatMap((line, i) => [...(i ? ['Shift+Enter'] : []), ...(line ? [`Type ${vhsString(line)}`] : [])]);
}

/** Matches Pi's footer once the TUI is up with the faux model. */
export const READY = 'demo • ';

export function buildTape(s: Scenario, t: TapeEnv): string {
  const lines: string[] = [
    `# Generated by demo/build.ts from ${s.name}. Do not edit.`,
    `Output ${vhsString(t.output)}`,
    'Set Shell "bash"',
    `Set Width ${s.terminal.width}`,
    `Set Height ${s.terminal.height}`,
    `Set FontSize ${s.terminal.fontSize}`,
    ...(s.terminal.fontFamily ? [`Set FontFamily ${vhsString(s.terminal.fontFamily)}`] : []),
    ...(s.terminal.theme ? [`Set Theme ${vhsString(s.terminal.theme)}`] : []),
    'Set TypingSpeed 35ms',
    'Set Padding 24',
    ...Object.entries(t.env).map(([k, v]) => `Env ${k} ${vhsString(v)}`),
    '',
    'Hide',
    `Type ${vhsString(`cd '${t.workdir}' && clear && ${t.pi}`)}`,
    'Enter',
    // Pi's footer names the model once the TUI is up: "demo • <thinking>", prefixed with "(faux) "
    // only when other providers are configured too.
    `Wait+Screen@30s ${vhsRegex(READY)}`,
    'Show',
    'Sleep 800ms',
  ];
  for (const turn of s.turns) {
    lines.push('');
    if ('prompt' in turn) {
      lines.push(...typeLines(turn.prompt), 'Sleep 400ms', 'Enter');
    } else {
      lines.push(...turn.tape.trim().split('\n').map((l) => l.trim()).filter(Boolean));
    }
    const wait = turn.wait ?? defaultWait(turn.reply);
    if (wait) lines.push(`Wait+Screen@60s ${vhsRegex(wait)}`);
    lines.push(`Sleep ${turn.pause ?? '2s'}`);
  }
  lines.push('');
  return lines.join('\n');
}
