// Re-grades recorded runs with the current oracle. No model is called: each run's answer.txt and the
// files it left (work/) are graded again, against the task's fixture as the state before the run.
//
//   node bench/rescore.ts                                   the archive bench/records/2026-11-27.tgz
//   node bench/rescore.ts <archive.tgz | dir> [--out <report.md>] [--records <dir>]
//
// The input holds one directory per spec: runs.jsonl and runs/<arm>/<class>__<name>/rep<N>/{answer.txt,work/}.
// --out writes the comparison (default: stdout); --records writes the re-graded runs.jsonl per spec, which
// `npm run bench -- --report <dir>/<spec>` reads.
import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import type { RunRecord } from './lib/run.ts';
import { DIMENSIONS, loadTasks, runOracle, snapshot, type Dimension, type Task } from './lib/task.ts';

export interface Rescored {
  spec: string;
  /** Where the run's files are, relative to the input. */
  path: string;
  old: RunRecord;
  /** The record under the current oracle; undefined when the run could not be graded again. */
  now?: RunRecord;
  skipped?: string;
  /** Old checks whose result the same check no longer reproduces (they should all reproduce). */
  drift: string[];
}

export function rescore(dir: string, tasks: Task[] = loadTasks()): Rescored[] {
  const byId = new Map(tasks.map(t => [t.id, t]));
  const before = new Map<string, Map<string, string>>();
  const out: Rescored[] = [];
  for (const spec of fs.readdirSync(dir).sort()) {
    const file = path.join(dir, spec, 'runs.jsonl');
    if (!fs.existsSync(file)) continue;
    for (const line of fs.readFileSync(file, 'utf8').split('\n').filter(Boolean)) {
      const old = JSON.parse(line) as RunRecord;
      const rel = path.join(spec, 'runs', old.arm, old.task.replace('/', '__'), `rep${old.rep}`);
      const task = byId.get(old.task), run = path.join(dir, rel);
      const skipped = !task ? 'the task no longer exists' : !fs.existsSync(path.join(run, 'work')) || !fs.existsSync(path.join(run, 'answer.txt')) ? 'answer.txt or work/ is missing' : undefined;
      if (!task || skipped) { out.push({ spec, path: rel, old, skipped, drift: [] }); continue; }
      if (!before.has(task.id)) before.set(task.id, snapshot(task.fixture));
      const grade = runOracle(task, path.join(run, 'work'), fs.readFileSync(path.join(run, 'answer.txt'), 'utf8'), before.get(task.id)!);
      const { dimensions: _d, extraFindings: _e, ...rest } = old;
      const now: RunRecord = {
        ...rest, taskVersion: task.version, pass: !old.timedOut && grade.pass, dimensions: grade.dimensions,
        ...(grade.extraFindings !== undefined ? { extraFindings: grade.extraFindings } : {}),
        checks: grade.checks, changed: grade.changed, outOfScope: grade.outOfScope,
      };
      const drift = old.checks.flatMap(c => { const same = grade.checks.find(n => n.check === c.check); return same && same.pass !== c.pass ? [c.check] : []; });
      if (old.changed.join('\n') !== grade.changed.join('\n')) drift.push(`changed files: recorded ${old.changed.join(', ') || 'none'}, found ${grade.changed.join(', ') || 'none'}`);
      out.push({ spec, path: rel, old, now, drift });
    }
  }
  return out;
}

const failing = (r: RunRecord) => r.checks.filter(c => !c.pass).map(c => `${c.dimension ?? 'outcome'}: ${c.detail ?? c.check}`).join('; ') + (r.timedOut ? '; timed out' : '');
const cell = (text: string) => text.replaceAll('|', '\\|').replaceAll('\n', ' ');

export function formatRescore(all: Rescored[], source: string): string {
  const done = all.filter(r => r.now), n = (xs: unknown[]) => xs.length;
  const dimCount = (rs: Rescored[], d: Dimension) => { const of = rs.flatMap(r => (r.now!.dimensions![d] === undefined ? [] : [r.now!.dimensions![d]!])); return of.length ? `${of.filter(Boolean).length}/${of.length}` : '–'; };
  const extras = (rs: Rescored[]) => (rs.some(r => r.now!.extraFindings !== undefined) ? `${rs.reduce((a, r) => a + (r.now!.extraFindings ?? 0), 0)} (${n(rs.filter(r => r.now!.extraFindings))})` : '–');
  const row = (rs: Rescored[]) => `${n(rs.filter(r => r.old.pass))}/${n(rs)} | ${n(rs.filter(r => r.now!.pass))}/${n(rs)} | ${DIMENSIONS.map(d => dimCount(rs, d)).join(' | ')} | ${extras(rs)}`;
  const versions = [...new Set(done.filter(r => r.old.taskVersion !== r.now!.taskVersion).map(r => `${r.old.task} v${r.old.taskVersion} → v${r.now!.taskVersion}`))].sort();
  const head = `old pass | strict pass | ${DIMENSIONS.join(' | ')} | extra findings (runs)`, rule = '---|---|---|---|---|---|---|---';
  const lines = [
    `# Re-grade of ${source}`, '',
    'Generated by `node bench/rescore.ts`: the recorded answers and files, graded again by the current oracle. No model was called.', '',
    '- old pass: the verdict in the record (every check of the oracle at the time).',
    '- strict pass: every dimension the task has now passes. Each dimension column is passes/runs it applies to.',
    '- extra findings: lines a review answer cited that belong to no bug, with the number of runs that had any. They fail nothing.', '',
    `${n(all)} recorded runs, ${n(done)} graded again${n(all) - n(done) ? `, ${n(all) - n(done)} skipped` : ''}. Task versions: ${versions.join(', ') || 'unchanged'}.`, '',
    '## By spec', '', `| spec | ${head} |`, `|---|${rule}|`,
  ];
  const specs = [...new Set(done.map(r => r.spec))];
  for (const spec of specs) lines.push(`| ${spec} | ${row(done.filter(r => r.spec === spec))} |`);
  lines.push(`| all | ${row(done)} |`, '', '## By spec, arm and task class');
  for (const spec of specs) {
    lines.push('', `### ${spec}`, '', `| arm | class | ${head} |`, `|---|---|${rule}|`);
    const of = done.filter(r => r.spec === spec);
    for (const key of [...new Set(of.map(r => `${r.old.arm}\0${r.old.taskClass}`))].sort()) {
      const rs = of.filter(r => `${r.old.arm}\0${r.old.taskClass}` === key);
      lines.push(`| ${key.replace('\0', ' | ')} | ${row(rs)} |`);
    }
  }
  const list = (title: string, note: string, rs: Rescored[], why: (r: Rescored) => string) => {
    lines.push('', `## ${title} (${n(rs)})`, '', note, '');
    if (!rs.length) { lines.push('None.'); return; }
    lines.push('| run (path in the archive) | old → new | why |', '|---|---|---|');
    for (const r of rs) lines.push(`| \`${r.path}\` | ${r.old.pass ? 'pass' : 'fail'} → ${r.now!.pass ? 'pass' : 'fail'} | ${cell(why(r))} |`);
  };
  const oldWhy = (r: Rescored) => `old: ${failing(r.old) || 'passed'}`;
  list('Verdict changed', 'Each path holds answer.txt and work/ for a person to check.', done.filter(r => r.old.pass !== r.now!.pass),
    r => (r.now!.pass ? `${oldWhy(r)}. Now every dimension passes${r.now!.extraFindings ? `, with ${r.now!.extraFindings} extra finding(s): ${r.now!.checks.find(c => c.extra)?.detail}` : ''}` : `now: ${failing(r.now!)}`));
  list('Still failing, by dimension', 'The verdict is the same; the dimensions say what failed.', done.filter(r => !r.old.pass && !r.now!.pass),
    r => `${oldWhy(r)}. Now: ${failing(r.now!)}${Object.entries(r.now!.dimensions!).some(([, ok]) => ok) ? ` (passes ${Object.entries(r.now!.dimensions!).filter(([, ok]) => ok).map(([d]) => d).join(', ')})` : ''}`);
  list('Strict pass with extra findings', 'These pass; the extra findings are the over-reporting the old oracle failed.', done.filter(r => r.now!.pass && r.now!.extraFindings),
    r => r.now!.checks.find(c => c.extra)?.detail ?? '');
  const drift = done.filter(r => r.drift.length), skipped = all.filter(r => !r.now);
  lines.push('', '## Consistency with the records', '',
    `Checks that exist in both oracles (commands, unchanged files, answers of unchanged tasks) and the list of changed files give the recorded result in ${n(done) - n(drift)} of ${n(done)} runs.`);
  for (const r of drift) lines.push(`- \`${r.path}\`: ${r.drift.join('; ')}`);
  for (const r of skipped) lines.push(`- skipped \`${r.path}\`: ${r.skipped}`);
  return lines.join('\n');
}

function main(argv: string[]) {
  const flag = (name: string) => { const i = argv.indexOf(name); return i >= 0 ? argv[i + 1] : undefined; };
  const input = argv.find((a, i) => !a.startsWith('--') && !['--out', '--records'].includes(argv[i - 1] ?? '')) ?? path.join(import.meta.dirname, 'records', '2026-11-27.tgz');
  let dir = input, temp: string | undefined;
  if (fs.statSync(input).isFile()) {
    dir = temp = fs.mkdtempSync(path.join(os.tmpdir(), 'calliopi-rescore-'));
    // The archive was made on macOS: skip its AppleDouble (._*) entries and tar's notes about them.
    const r = spawnSync('tar', ['-xzf', path.resolve(input), '--exclude', '._*', '-C', dir], { encoding: 'utf8' });
    if (r.status !== 0) throw new Error(`tar: ${r.stderr.trim().split('\n').at(-1)}`);
  }
  try {
    const all = rescore(dir);
    const report = formatRescore(all, path.basename(input));
    const out = flag('--out'), records = flag('--records');
    if (out) fs.writeFileSync(out, `${report}\n`); else console.log(report);
    if (records) for (const spec of new Set(all.map(r => r.spec))) {
      fs.mkdirSync(path.join(records, spec), { recursive: true });
      fs.writeFileSync(path.join(records, spec, 'runs.jsonl'), all.filter(r => r.spec === spec && r.now).map(r => `${JSON.stringify(r.now)}\n`).join(''));
    }
    const done = all.filter(r => r.now);
    console.error(`${all.length} runs: ${done.length} graded again, ${done.filter(r => r.old.pass !== r.now!.pass).length} verdicts changed, ${done.filter(r => r.drift.length).length} with drift${out ? ` → ${out}` : ''}`);
  } finally { if (temp) fs.rmSync(temp, { recursive: true, force: true }); }
}

if (process.argv[1] && path.resolve(process.argv[1]) === import.meta.filename) main(process.argv.slice(2));
